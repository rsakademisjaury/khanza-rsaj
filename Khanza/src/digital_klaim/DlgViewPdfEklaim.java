// ==== Upload EKLAIM (Individual) → berkas_digital_perawatan (kode 009) ====
private void uploadEklaimIndividual() {
    this.setCursor(java.awt.Cursor.getPredefinedCursor(java.awt.Cursor.WAIT_CURSOR));
    try {
        final String namaPdf = txtNameFile.getText() == null ? "" : txtNameFile.getText().trim();
        if (namaPdf.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Nama file PDF kosong.");
            return;
        }

        // PDF asal viewer
        java.io.File pdfFile = new java.io.File("tempPDF/" + namaPdf);
        if (!pdfFile.exists()) {
            javax.swing.JOptionPane.showMessageDialog(this, "File tidak ditemukan: " + pdfFile.getAbsolutePath());
            return;
        }

        // Ekstrak NO_SEP dari nama file (contoh: EKLAIM_0342R0491025V002435.pdf)
        final String noSep = extractNoSepFromPdfName(namaPdf);
        if (noSep.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Gagal mengekstrak No. SEP dari nama file: " + namaPdf);
            return;
        }

        // Ambil no_rawat dari bridging_sep
        String noRawat = Sequel.cariIsi(
                "SELECT IFNULL(no_rawat,'') FROM bridging_sep WHERE no_sep=? LIMIT 1",
                noSep
        );
        if (noRawat == null || noRawat.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "No.Rawat tidak ditemukan untuk No.SEP: " + noSep + " (cek tabel bridging_sep)",
                    "Data tidak ditemukan",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );
            return;
        }
        noRawat = noRawat.trim();
        txtNoRawat.setText(noRawat); // opsional: tampilkan di form bila ada field ini

        // baseName untuk nama JPG konsisten (tanpa .pdf)
        final String baseName = namaPdf.replaceAll("(?i)\\.pdf$", "");
        final String kodeBerkas = getKodeBerkasIndividual(); // contoh: "009"

        // =========================================================
        // HAPUS INDIVIDUAL LAMA (TIMPA, BUKAN CEGAH DUPLIKAT LAGI)
        // =========================================================
        try {
            java.util.List<String> lokasiLama = new java.util.ArrayList<>();

            try (java.sql.PreparedStatement psOld = koneksi.prepareStatement(
                    "SELECT lokasi_file FROM berkas_digital_perawatan WHERE no_rawat=? AND kode=?"
            )) {
                psOld.setString(1, noRawat);
                psOld.setString(2, kodeBerkas);

                try (java.sql.ResultSet rsOld = psOld.executeQuery()) {
                    while (rsOld.next()) {
                        String lok = rsOld.getString("lokasi_file");
                        if (lok != null && !lok.trim().isEmpty()) {
                            lokasiLama.add(lok.trim());
                        }
                    }
                }
            }

            if (!lokasiLama.isEmpty()) {
                // Hapus data lama di DB
                Sequel.queryu(
                        "DELETE FROM berkas_digital_perawatan WHERE no_rawat='" + noRawat + "' AND kode='" + kodeBerkas + "'"
                );

                // Hapus file JPG lama di folder berkasrawat
                for (String lok : lokasiLama) {
                    java.io.File f = new java.io.File("berkasrawat/" + lok);
                    if (f.exists() && f.isFile()) {
                        if (!f.delete()) {
                            System.out.println("Gagal menghapus file Individual lama: " + f.getAbsolutePath());
                        }
                    }
                }
            }
        } catch (Exception exDel) {
            System.out.println("Gagal membersihkan berkas Individual lama: " + exDel.getMessage());
            // kalau gagal bersih-bersih, tetap lanjut upload baru supaya user tidak terganggu
        }
        // ============= AKHIR HAPUS LAMA =========================

        // Konversi PDF → multi-JPG 300 DPI
        java.util.List<java.io.File> jpgFiles = convertPdfToJpgMulti_Eklaim(pdfFile, baseName);
        if (jpgFiles.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Konversi PDF→JPG gagal / tidak ada halaman.");
            return;
        }

        // Upload setiap halaman
        final String docpath = "berkasrawat/pages/upload/";
        int sukses = 0;
        for (java.io.File jpg : jpgFiles) {
            if (uploadOneJpg(jpg, docpath)) {
                final String lokasiFile = "pages/upload/" + jpg.getName();
                boolean ok = Sequel.menyimpantf(
                        "berkas_digital_perawatan", "?,?,?", "No.Rawat", 3,
                        new String[]{ noRawat, kodeBerkas, lokasiFile }
                );
                if (ok) {
                    sukses++;
                }
            }
        }

        // Bersih-bersih tmp JPG
        cleanupTmpJpg(baseName);

        if (sukses > 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Upload Individual selesai. (" + sukses + " halaman)");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Tidak ada halaman yang berhasil diupload.");
        }

    } catch (Exception e) {
        System.out.println("uploadEklaimIndividual err: " + e.getMessage());
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Upload gagal: " + e.getMessage(),
                "Kesalahan",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    } finally {
        this.setCursor(java.awt.Cursor.getDefaultCursor());
    }
}

