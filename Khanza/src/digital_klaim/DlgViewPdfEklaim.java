// Ambil NO_SEP dari nama file PDF.
// - "EKLAIM_<NOSEP>.pdf"            -> <NOSEP>
// - "EKLAIM_<NOSEP>_ANGKAUNIK.pdf"  -> <NOSEP> (abaikan ANGKAUNIK)
// - "<PREFIX>_<NOSEP>.pdf" (lainnya)-> <NOSEP> (bagian setelah '_' terakhir)
private String extractNoSepFromPdfName(String namaPdf) {
    if (namaPdf == null) return "";

    String path = namaPdf.trim();

    // Ambil hanya nama file tanpa path
    int slash = Math.max(path.lastIndexOf('/'), path.lastIndexOf('\\'));
    String fileName = (slash >= 0) ? path.substring(slash + 1) : path;

    final String PREFIX = "EKLAIM_";

    // Kalau diawali "EKLAIM_", pakai parser khusus (supaya "_ANGKAUNIK" diabaikan)
    if (fileName.regionMatches(true, 0, PREFIX, 0, PREFIX.length())) {
        // Gunakan helper yang sudah kamu punya untuk nama file EKLAIM_
        // (handle juga .pdf dan path kalau ada)
        return extractSepFromEklaimFilename(fileName);
    }

    // Fallback lama: ambil bagian setelah underscore terakhir
    String base = fileName.replaceAll("(?i)\\.pdf$", "");
    int idx = base.lastIndexOf('_');
    String token = (idx >= 0) ? base.substring(idx + 1) : base;
    return token.replaceAll("[^A-Za-z0-9]", "");
}

private static String extractSepFromEklaimFilename(String fileName) {
            if (fileName == null) return "";
            String base = fileName.trim();
            int slash = Math.max(base.lastIndexOf('/'), base.lastIndexOf('\\'));
            if (slash >= 0) base = base.substring(slash + 1);
            int q = base.indexOf('?');
            if (q >= 0) base = base.substring(0, q);
            int dot = base.lastIndexOf('.');
            if (dot > 0) base = base.substring(0, dot);
            final String PREFIX = "EKLAIM_";
            if (base.regionMatches(true, 0, PREFIX, 0, PREFIX.length())) {
                base = base.substring(PREFIX.length());
            }
            String[] parts = base.split("_", 2);
            if (parts.length == 0) return "";
            return parts[0].replaceAll("\\s+", "");
        }


private String normalizeSep(String raw) {
            if (raw == null) return "";
            String s = raw.trim();
            if (s.matches("\\d{10,18}")) {
                String sep;
                try { sep = Sequel.cariIsi("SELECT no_sep FROM inacbg_klaim_baru WHERE nomor_klaim=?", s);
                } catch (Exception e) { sep = ""; }
                if (sep != null && !sep.isEmpty()) return sep;
                try { sep = Sequel.cariIsi("SELECT no_sep FROM inacbg_final_klaim WHERE nomor_klaim=?", s);
                } catch (Exception e) { sep = ""; }
                if (sep != null && !sep.isEmpty()) return sep;
                try { sep = Sequel.cariIsi("SELECT no_sep FROM inacbg_klaim_baru WHERE no_klaim=?", s);
                } catch (Exception e) { sep = ""; }
                if (sep != null && !sep.isEmpty()) return sep;
                try { sep = Sequel.cariIsi("SELECT no_sep FROM inacbg_data_klaim WHERE nomor_klaim=?", s);
                } catch (Exception e) { sep = ""; }
                if (sep != null && !sep.isEmpty()) return sep;
                return s;
            }
            return s;
        }


