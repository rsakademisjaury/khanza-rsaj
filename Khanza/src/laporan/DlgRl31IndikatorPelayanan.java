private String getLabelPeriode(String tglAwal, String tglAkhir) {
    try {
        LocalDate awal = LocalDate.parse(tglAwal);
        LocalDate akhir = LocalDate.parse(tglAkhir);

        if (awal.getYear() == akhir.getYear()
                && awal.getMonthValue() == 1
                && awal.getDayOfMonth() == 1
                && akhir.getMonthValue() == 12
                && akhir.getDayOfMonth() == 31) {
            return "Tahun " + awal.getYear();
        }

        if (awal.getYear() == akhir.getYear()
                && awal.getMonthValue() == akhir.getMonthValue()
                && awal.getDayOfMonth() == 1
                && akhir.getDayOfMonth() == akhir.lengthOfMonth()) {
            return getNamaBulanIndonesia(awal.getMonthValue()) + " " + awal.getYear();
        }

        return tanggalIndonesia(awal) + " s.d. " + tanggalIndonesia(akhir);
    } catch (Exception e) {
        return Tgl1.getSelectedItem() + " s.d. " + Tgl2.getSelectedItem();
    }
}

private String tanggalIndonesia(LocalDate tanggal) {
    return String.format("%02d %s %d", tanggal.getDayOfMonth(), getNamaBulanIndonesia(tanggal.getMonthValue()), tanggal.getYear());
}

private String getNamaBulanIndonesia(int bulan) {
    String[] namaBulan = {
        "", "Januari", "Februari", "Maret", "April", "Mei", "Juni",
        "Juli", "Agustus", "September", "Oktober", "November", "Desember"
    };
    if (bulan >= 1 && bulan <= 12) {
        return namaBulan[bulan];
    }
    return "";
}

private String kondisiKategori(String kategori) {
    if (kategori.equals("SEMUA")) {
        return "1=1";
    }
    String kolom = "UPPER(CONCAT(IFNULL(k.kelas,''),' ',IFNULL(b.nm_bangsal,'')))";
    String icu = "(" + kolom + " LIKE '%ICU%' AND " + kolom + " NOT LIKE '%NICU%' AND " + kolom + " NOT LIKE '%PICU%' AND " + kolom + " NOT LIKE '%RICU%' AND " + kolom + " NOT LIKE '%ICCU%' AND " + kolom + " NOT LIKE '%ICVCU%' AND " + kolom + " NOT LIKE '%HCU%')";
    String nicu = "(" + kolom + " LIKE '%NICU%')";
    String picu = "(" + kolom + " LIKE '%PICU%')";
    String intensifLainnya = "(" + kolom + " LIKE '%HCU%' OR " + kolom + " LIKE '%ICCU%' OR " + kolom + " LIKE '%ICVCU%' OR " + kolom + " LIKE '%RICU%')";

    if (kategori.equals("ICU")) {
        return icu;
    } else if (kategori.equals("NICU")) {
        return nicu;
    } else if (kategori.equals("PICU")) {
        return picu;
    } else if (kategori.equals("INTENSIF_LAINNYA")) {
        return intensifLainnya;
    } else {
        return "NOT (" + icu + " OR " + nicu + " OR " + picu + " OR " + intensifLainnya + ")";
    }
}

