private void tampil() {
    Valid.tabelKosong(tabMode);

    try {
        String tglAwal = Valid.SetTgl(Tgl1.getSelectedItem() + "");
        String tglAkhir = Valid.SetTgl(Tgl2.getSelectedItem() + "");

        String[][] jenisPelayanan = {
            {"1", "Non Intensif", "NON_INTENSIF"},
            {"2", "ICU", "ICU"},
            {"3", "NICU", "NICU"},
            {"4", "PICU", "PICU"},
            {"5", "Intensif lainnya", "INTENSIF_LAINNYA"}
        };

        double[] jumlahBOR = new double[1];
        double[] jumlahALOS = new double[1];
        double[] jumlahBTO = new double[1];
        double[] jumlahTOI = new double[1];
        double[] jumlahNDR = new double[1];
        double[] jumlahGDR = new double[1];
        int[] isiBOR = new int[1];
        int[] isiALOS = new int[1];
        int[] isiBTO = new int[1];
        int[] isiTOI = new int[1];
        int[] isiNDR = new int[1];
        int[] isiGDR = new int[1];

        int jumlahHariPeriode = getJumlahHariDalamPeriode(tglAwal, tglAkhir);

        for (String[] jp : jenisPelayanan) {
            DataIndikator data = hitungIndikator(jp[2], tglAwal, tglAkhir, jumlahHariPeriode);

            if (data.tt > 0) {
                jumlahBOR[0] += data.bor;
                isiBOR[0]++;
                jumlahBTO[0] += data.bto;
                isiBTO[0]++;
            }
            if (data.pasienKeluar > 0) {
                jumlahALOS[0] += data.alos;
                isiALOS[0]++;
                jumlahNDR[0] += data.ndr;
                isiNDR[0]++;
                jumlahGDR[0] += data.gdr;
                isiGDR[0]++;
            }
            if (data.tt > 0 && data.pasienKeluar > 0) {
                jumlahTOI[0] += data.toi;
                isiTOI[0]++;
            }

            tambahBaris(jp[0], jp[1], data.bor, data.alos, data.bto, data.toi, data.ndr, data.gdr);
        }

        tambahBaris(
            "77",
            "Rata-rata",
            isiBOR[0] > 0 ? jumlahBOR[0] / isiBOR[0] : 0,
            isiALOS[0] > 0 ? jumlahALOS[0] / isiALOS[0] : 0,
            isiBTO[0] > 0 ? jumlahBTO[0] / isiBTO[0] : 0,
            isiTOI[0] > 0 ? jumlahTOI[0] / isiTOI[0] : 0,
            isiNDR[0] > 0 ? jumlahNDR[0] / isiNDR[0] : 0,
            isiGDR[0] > 0 ? jumlahGDR[0] / isiGDR[0] : 0
        );

        // Model 2: rekap ringkas satu baris sesuai periode filter.
        // Ini untuk kebutuhan pembanding/internal, sedangkan model 1 di atas tetap mengikuti baris Juknis.
        DataIndikator dataTotal = hitungIndikator("SEMUA", tglAwal, tglAkhir, jumlahHariPeriode);
        tambahPemisahModelRingkas();
        tambahBaris(
            "1",
            getLabelPeriode(tglAwal, tglAkhir),
            dataTotal.bor,
            dataTotal.alos,
            dataTotal.bto,
            dataTotal.toi,
            dataTotal.ndr,
            dataTotal.gdr
        );
    } catch (Exception e) {
        System.out.println("Error tampil RL 3.1: " + e);
    }
}

private void tambahBaris(String no, String jenisPelayanan, double bor, double alos, double bto, double toi, double ndr, double gdr) {
    String kataKunci = TCari.getText().trim().toLowerCase();
    if (!kataKunci.equals("") && !(no.toLowerCase().contains(kataKunci) || jenisPelayanan.toLowerCase().contains(kataKunci))) {
        return;
    }

    tabMode.addRow(new Object[]{
        no,
        jenisPelayanan,
        angka(bor),
        angka(alos),
        angka(bto),
        angka(toi),
        angka(ndr),
        angka(gdr)
    });
}

private void tambahPemisahModelRingkas() {
    String kataKunci = TCari.getText().trim();
    if (!kataKunci.equals("")) {
        return;
    }
    tabMode.addRow(new Object[]{
        "",
        "MODEL 2 / RINGKAS",
        "",
        "",
        "",
        "",
        "",
        ""
    });
}

private DataIndikator hitungIndikator(String kategori, String tglAwal, String tglAkhir, int jumlahHariPeriode) throws SQLException {
    DataIndikator data = new DataIndikator();
    data.tt = getJumlahTempatTidur(kategori);
    data.hariPerawatan = getJumlahHariPerawatan(kategori, tglAwal, tglAkhir);
    data.lamaDirawat = getJumlahLamaDirawat(kategori, tglAwal, tglAkhir);
    data.pasienKeluar = getJumlahPasienKeluarHidupMati(kategori, tglAwal, tglAkhir);
    data.matiLebih48 = getJumlahPasienMatiLebih48Jam(kategori, tglAwal, tglAkhir);
    data.matiTotal = getJumlahPasienMati(kategori, tglAwal, tglAkhir);

    data.bor = data.tt > 0 && jumlahHariPeriode > 0 ? (double) data.hariPerawatan / (data.tt * jumlahHariPeriode) * 100 : 0;
    data.alos = data.pasienKeluar > 0 ? (double) data.lamaDirawat / data.pasienKeluar : 0;
    data.bto = data.tt > 0 ? (double) data.pasienKeluar / data.tt : 0;
    data.toi = data.pasienKeluar > 0 && data.tt > 0 ? (double) ((data.tt * jumlahHariPeriode) - data.hariPerawatan) / data.pasienKeluar : 0;
    data.ndr = data.pasienKeluar > 0 ? (double) data.matiLebih48 / data.pasienKeluar * 1000 : 0;
    data.gdr = data.pasienKeluar > 0 ? (double) data.matiTotal / data.pasienKeluar * 1000 : 0;

    return data;
}

