private void simpanTB() {
    // Ambil nilai dari UI
    String noRawat = TNoRwCari.getText().trim();
    String sitb    = null;

    if (R1.isSelected()) {
        sitb = "Sudah Ada";
    } else if (R2.isSelected()) {
        sitb = "Belum Ada";
    }

    // keterangan diisi "Terindikasi TB" kalau checkbox dicentang, jika tidak -> NULL
    String ket = CheckBoxYA.isSelected() ? "Terindikasi TB" : null;

    // NoSITB & Tindak Lanjut
    String noSITB        = (NoSITB.getText() != null) ? NoSITB.getText().trim() : "";
    String tindakLanjut  = (TindakLanjut.getText() != null) ? TindakLanjut.getText().trim() : "";

    // Validasi minimal
    if (noRawat.isEmpty()) {
        JOptionPane.showMessageDialog(this, "No. Rawat belum diisi.");
        return;
    }
    if (sitb == null) {
        JOptionPane.showMessageDialog(this, "Pilih status SI-TB: Sudah Ada / Belum Ada.");
        return;
    }

    // Wajib isi NoSITB jika "Sudah Ada"
    if ("Sudah Ada".equals(sitb) && noSITB.isEmpty()) {
        JOptionPane.showMessageDialog(this, "No. SITB wajib diisi untuk status 'Sudah Ada'.");
        NoSITB.requestFocus();
        return;
    }

    // Validasi panjang digit NoSITB (abaikan non-digit saat menghitung)
    String noSITBDigits = noSITB.replaceAll("\\D", "");
    if (!noSITB.isEmpty() && noSITBDigits.length() > 16) {
        JOptionPane.showMessageDialog(this, "Maaf, No.SITB lebih dari 16 digit, silahkan cek kembali.");
        NoSITB.requestFocus();
        return;
    }

    // Ambil no_rkm_medis dari reg_periksa berdasarkan no_rawat
    String noRM = "";
    try (PreparedStatement psRM = koneksi.prepareStatement(
            "SELECT no_rkm_medis FROM reg_periksa WHERE no_rawat=? LIMIT 1")) {
        psRM.setString(1, noRawat);
        try (ResultSet rsRM = psRM.executeQuery()) {
            if (rsRM.next()) {
                noRM = rsRM.getString("no_rkm_medis");
            }
        }
    } catch (Exception ex) {
        System.out.println("Notifikasi ambil no_rkm_medis : " + ex.getMessage());
    }
    if (noRM == null || noRM.trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "No. RM tidak ditemukan untuk No. Rawat tersebut.");
        return;
    }

    String sql = "INSERT INTO terindikasi_tb (no_rawat, sitb, keterangan, no_sitb, tindak_lanjut, no_rkm_medis) "
               + "VALUES (?, ?, ?, ?, ?, ?) "
               + "ON DUPLICATE KEY UPDATE "
               + "  sitb=VALUES(sitb), "
               + "  keterangan=VALUES(keterangan), "
               + "  no_sitb=VALUES(no_sitb), "
               + "  tindak_lanjut=VALUES(tindak_lanjut), "
               + "  no_rkm_medis=VALUES(no_rkm_medis)";

    try (PreparedStatement ps = koneksi.prepareStatement(sql)) {
        // 1 no_rawat
        ps.setString(1, noRawat);
        // 2 sitb
        ps.setString(2, sitb);
        // 3 keterangan
        if (ket == null) ps.setNull(3, java.sql.Types.VARCHAR); else ps.setString(3, ket);
        // 4 no_sitb
        if (noSITB.isEmpty()) ps.setNull(4, java.sql.Types.VARCHAR); else ps.setString(4, noSITB);
        // 5 tindak_lanjut (TEXT di DB tetap pakai setString)
        if (tindakLanjut.isEmpty()) ps.setNull(5, java.sql.Types.VARCHAR); else ps.setString(5, tindakLanjut);
        // 6 no_rkm_medis (varchar(6))
        ps.setString(6, noRM.trim());

        ps.executeUpdate();
        JOptionPane.showMessageDialog(this, "Verifikasi TB berhasil disimpan.");
        dispose(); // tutup dialog setelah sukses
    } catch (Exception e) {
        System.out.println("Notifikasi simpanTB : " + e.getMessage());
        JOptionPane.showMessageDialog(this, "Gagal menyimpan verifikasi TB.\n" + e.getMessage());
    }
}

