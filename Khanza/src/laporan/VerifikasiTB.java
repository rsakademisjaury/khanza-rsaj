    /**
     * Set No. Rawat dari luar form dan langsung memuat data jika ada.
     */
    public void setNoRawat(String noRawat) {
        if (noRawat == null) noRawat = "";
        TNoRwCari.setText(noRawat.trim());
        if (!noRawat.trim().isEmpty()) {
            muatData();
            updateIdentitasPasien();

        }
    }

    /**
     * Muat data dari tabel terindikasi_tb berdasarkan no_rawat
     * dan sinkronkan ke UI.
     */
    private void muatData() {
        String noRawat = TNoRwCari.getText().trim();
        if (noRawat.isEmpty()) {
            return;
        }
        String sql = "SELECT sitb, keterangan FROM terindikasi_tb WHERE no_rawat=?";
        try (PreparedStatement ps = koneksi.prepareStatement(sql)) {
            ps.setString(1, noRawat);
            try (ResultSet rs = ps.executeQuery()) {
                if (rs.next()) {
                    String sitb = rs.getString("sitb");
                    String ket  = rs.getString("keterangan");
                    if ("Sudah Ada".equalsIgnoreCase(sitb)) {
                        R1.setSelected(true);
                    } else {
                        R2.setSelected(true);
                    }
                    CheckBoxYA.setSelected(ket != null && !ket.trim().isEmpty());
                } else {
                    // default jika belum ada data
                    R2.setSelected(true);
                    CheckBoxYA.setSelected(false);
                }
            }
        } catch (Exception e) {
            System.out.println("Notifikasi muatData : " + e.getMessage());
        }
        updateIdentitasPasien();

    }
    
