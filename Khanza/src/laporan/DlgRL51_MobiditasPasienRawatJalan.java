private void prosesCari() {
    this.setCursor(Cursor.getPredefinedCursor(Cursor.WAIT_CURSOR));
    try {
        htmlContent = new StringBuilder();
        htmlContent.append("<html><body><table width='100%' border='0' align='center' cellpadding='3px' cellspacing='0' class='isi'>");
        htmlContent.append("<tr class='header'>"
            + "<td bgcolor='#F7F7F7' align='center' rowspan='3'>No. Urut</td>"
            + "<td bgcolor='#F7F7F7' align='center' rowspan='3'>Kode ICD-10</td>"
            + "<td bgcolor='#F7F7F7' align='center' rowspan='3'>Deskripsi Penyakit</td>"
            + "<td bgcolor='#F7F7F7' align='center' colspan='50'>Jumlah Kasus Baru Menurut Kelompok Umur & Jenis Kelamin</td>"
            + "<td bgcolor='#F7F7F7' align='center' colspan='3' rowspan='2'>Jumlah Kasus Baru</td>"
            + "<td bgcolor='#F7F7F7' align='center' colspan='3' rowspan='2'>Jumlah Kunjungan</td></tr>");

        String[] umurKelompok = {"<1 jam", "1-23 jam", "1-7 hari", "8-28 hari", "29 hari-<3 bulan", "3-<6 bulan", "6-11 bulan", "1-4 tahun", "5-9 tahun", "10-14 tahun", "15-19 tahun", "20-24 tahun", "25-29 tahun", "30-34 tahun", "35-39 tahun", "40-44 tahun", "45-49 tahun", "50-54 tahun", "55-59 tahun", "60-64 tahun", "65-69 tahun", "70-74 tahun", "75-79 tahun", "80-84 tahun", "≥85 tahun"};

        htmlContent.append("<tr class='header'>");
        for (String kelompok : umurKelompok) {
            htmlContent.append("<td bgcolor='#F7F7F7' align='center' colspan='2'>").append(kelompok).append("</td>");
        }
        htmlContent.append("</tr>");

        htmlContent.append("<tr class='header'>");
        for (int j = 0; j < umurKelompok.length; j++) {
            htmlContent.append("<td bgcolor='#F7F7F7' align='center'>L</td><td bgcolor='#F7F7F7' align='center'>P</td>");
        }
        htmlContent.append("<td bgcolor='#F7F7F7' align='center'>L</td><td bgcolor='#F7F7F7' align='center'>P</td><td bgcolor='#F7F7F7' align='center'>Total</td>");
        htmlContent.append("<td bgcolor='#F7F7F7' align='center'>L</td><td bgcolor='#F7F7F7' align='center'>P</td><td bgcolor='#F7F7F7' align='center'>Total</td>");
        htmlContent.append("</tr>");

        String tgl1 = Valid.SetTgl(Tgl1.getSelectedItem() + "");
        String tgl2 = Valid.SetTgl(Tgl2.getSelectedItem() + "");

        String query = "SELECT dp.kd_penyakit, SUBSTRING(pyk.nm_penyakit,1,80) AS nm_penyakit, " +
                       "p.jk, rp.umurdaftar, rp.sttsumur, " +
                       "CASE WHEN NOT EXISTS ( " +
                       "    SELECT 1 FROM diagnosa_pasien dp2 " +
                       "    INNER JOIN reg_periksa rp2 ON dp2.no_rawat = rp2.no_rawat " +
                       "    WHERE dp2.status = 'Ralan' AND dp2.prioritas = 1 " +
                       "    AND rp2.no_rkm_medis = rp.no_rkm_medis " +
                       "    AND dp2.kd_penyakit = dp.kd_penyakit " +
                       "    AND (rp2.tgl_registrasi < rp.tgl_registrasi " +
                       "         OR (rp2.tgl_registrasi = rp.tgl_registrasi AND rp2.jam_reg < rp.jam_reg) " +
                       "         OR (rp2.tgl_registrasi = rp.tgl_registrasi AND rp2.jam_reg = rp.jam_reg AND rp2.no_rawat < rp.no_rawat)) " +
                       ") THEN 'Baru' ELSE 'Lama' END AS status_kasus " +
                       "FROM diagnosa_pasien dp " +
                       "INNER JOIN penyakit pyk ON dp.kd_penyakit = pyk.kd_penyakit " +
                       "INNER JOIN reg_periksa rp ON dp.no_rawat = rp.no_rawat " +
                       "INNER JOIN pasien p ON rp.no_rkm_medis = p.no_rkm_medis " +
                       "WHERE dp.status = 'Ralan' AND dp.prioritas = 1 " +
                       "AND rp.tgl_registrasi BETWEEN ? AND ? " +
                       "ORDER BY dp.kd_penyakit, rp.tgl_registrasi, rp.jam_reg, rp.no_rawat";

        ps = koneksi.prepareStatement(query);
        ps.setString(1, tgl1);
        ps.setString(2, tgl2);
        rs = ps.executeQuery();

        Map<String, int[]> kasusBaruLaki = new HashMap<>();
        Map<String, int[]> kasusBaruPerempuan = new HashMap<>();
        Map<String, int[]> semuaKunjunganL = new HashMap<>();
        Map<String, int[]> semuaKunjunganP = new HashMap<>();
        Map<String, String> namaPenyakitMap = new HashMap<>();

        while (rs.next()) {
            String kode = rs.getString("kd_penyakit");
            String nama = rs.getString("nm_penyakit");
            String jk = rs.getString("jk");
            int umur = rs.getInt("umurdaftar");
            String sttsUmur = rs.getString("sttsumur");
            boolean kasusBaru = "Baru".equals(rs.getString("status_kasus"));

            int usiaJam = hitungUsiaJam(umur, sttsUmur);
            int kelompok = KelompokUmur.getIndex(usiaJam);

            if (kode != null && jk != null && kelompok >= 0 && isValidForGender(kode, jk) && isValidForAge(kode, umur, sttsUmur)) {
                if (jk.equalsIgnoreCase("L")) {
                    semuaKunjunganL.computeIfAbsent(kode, k -> new int[25])[kelompok]++;
                    if (kasusBaru) {
                        kasusBaruLaki.computeIfAbsent(kode, k -> new int[25])[kelompok]++;
                    }
                } else if (jk.equalsIgnoreCase("P")) {
                    semuaKunjunganP.computeIfAbsent(kode, k -> new int[25])[kelompok]++;
                    if (kasusBaru) {
                        kasusBaruPerempuan.computeIfAbsent(kode, k -> new int[25])[kelompok]++;
                    }
                }
                namaPenyakitMap.put(kode, nama);
            }
        }

        String[] daftarKode = namaPenyakitMap.keySet().toArray(new String[0]);
        Arrays.sort(daftarKode);

        int noUrut = 1;
        for (String kode : daftarKode) {
            String nama = namaPenyakitMap.get(kode);
            int[] umurBaruL = kasusBaruLaki.getOrDefault(kode, new int[25]);
            int[] umurBaruP = kasusBaruPerempuan.getOrDefault(kode, new int[25]);
            int[] kunjL = semuaKunjunganL.getOrDefault(kode, new int[25]);
            int[] kunjP = semuaKunjunganP.getOrDefault(kode, new int[25]);

            int totalBaruL = Arrays.stream(umurBaruL).sum();
            int totalBaruP = Arrays.stream(umurBaruP).sum();
            int totalKunjL = Arrays.stream(kunjL).sum();
            int totalKunjP = Arrays.stream(kunjP).sum();
            int totalBaru = totalBaruL + totalBaruP;
            int totalKunj = totalKunjL + totalKunjP;

            htmlContent.append("<tr class='isi'><td align='center'>").append(noUrut++).append("</td><td align='center'>")
                .append(htmlEscape(kode)).append("</td><td>").append(htmlEscape(nama)).append("</td>");
            for (int j = 0; j < 25; j++) {
                htmlContent.append("<td align='center'>").append(umurBaruL[j]).append("</td><td align='center'>").append(umurBaruP[j]).append("</td>");
            }
            htmlContent.append("<td align='center'>").append(totalBaruL).append("</td><td align='center'>")
                .append(totalBaruP).append("</td><td align='center'>").append(totalBaru).append("</td>");
            htmlContent.append("<td align='center'>").append(totalKunjL).append("</td><td align='center'>")
                .append(totalKunjP).append("</td><td align='center'>").append(totalKunj).append("</td></tr>");
        }

        htmlContent.append("</table></body></html>");
        LoadHTML.setText(htmlContent.toString());
    } catch (Exception e) {
        System.out.println("Notifikasi prosesCariRL51: " + e);
    } finally {
        try {
            if (rs != null) {
                rs.close();
            }
            if (ps != null) {
                ps.close();
            }
        } catch (Exception e) {
            System.out.println("Notifikasi prosesCariRL51 close: " + e);
        }
        this.setCursor(Cursor.getDefaultCursor());
    }
}    
