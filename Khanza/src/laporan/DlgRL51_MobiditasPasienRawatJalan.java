// Cek berdasarkan kelompok umur sesuai aturan ICD-10 RL 5.1.
private boolean isValidForAge(String kode, int umur, String satuan) {
    int umurJam = hitungUsiaJam(umur, satuan);
    if (umurJam < 0) {
        return false;
    }

    // Tidak digunakan pada rawat jalan: O60-O75, O80-O84, O85-O92, P95, dan Z38.
    if (kodeDalamRange(kode, "O60", "O75") || kodeDalamRange(kode, "O80", "O84") || kodeDalamRange(kode, "O85", "O92") || kodeSamaAtauTurunan(kode, "P95") || kodeSamaAtauTurunan(kode, "Z38")) {
        return false;
    }

    // Kode obstetri O00-O99 yang masih boleh di rawat jalan serta Z32-Z37 dan Z39: umur 10 s.d. <65 tahun.
    if ((kodeDalamRange(kode, "O00", "O99") || kodeDalamRange(kode, "Z32", "Z37") || kodeSamaAtauTurunan(kode, "Z39"))) {
        return umurJam >= (10 * 365 * 24) && umurJam < (65 * 365 * 24);
    }

    // Kode perinatal P01-P94 dan P96: hanya umur <28 hari.
    if (kodeDalamRange(kode, "P01", "P94") || kodeSamaAtauTurunan(kode, "P96")) {
        return umurJam < (28 * 24);
    }

    // Z00.1: umur sampai kelompok 10-14 tahun.
    if (kodeSamaAtauTurunan(kode, "Z00.1")) {
        return umurJam < (15 * 365 * 24);
    }

    // Z30-Z31: umur >=10 tahun.
    if (kodeDalamRange(kode, "Z30", "Z31")) {
        return umurJam >= (10 * 365 * 24);
    }

    return true;
}

private int hitungUsiaJam(int umur, String satuan) {
    if (satuan == null) {
        return -1;
    }
    switch (satuan) {
        case "Hr": return umur * 24;
        case "Bl": return umur * 30 * 24;
        case "Th": return umur * 365 * 24;
        default: return -1;
    }
}

private boolean kodeDalamDaftar(String kode, String[] daftarKode) {
    for (String item : daftarKode) {
        if (kodeSamaAtauTurunan(kode, item)) {
            return true;
        }
    }
    return false;
}

private boolean kodeSamaAtauTurunan(String kode, String induk) {
    if (kode == null || induk == null) {
        return false;
    }
    String kodeNorm = kode.trim().toUpperCase();
    String indukNorm = induk.trim().toUpperCase();
    return kodeNorm.equals(indukNorm) || kodeNorm.startsWith(indukNorm + ".") || (indukNorm.contains(".") && kodeNorm.startsWith(indukNorm));
}

private boolean kodeDalamRange(String kode, String awal, String akhir) {
    if (kode == null || awal == null || akhir == null) {
        return false;
    }
    String k = kode.trim().toUpperCase().replace(".", "");
    String a = awal.trim().toUpperCase().replace(".", "");
    String b = akhir.trim().toUpperCase().replace(".", "");
    if (k.length() < 3 || a.length() < 3 || b.length() < 3) {
        return false;
    }
    if (k.charAt(0) != a.charAt(0) || k.charAt(0) != b.charAt(0)) {
        return false;
    }
    try {
        int nilai = Integer.parseInt(k.substring(1, 3));
        int nilaiAwal = Integer.parseInt(a.substring(1, 3));
        int nilaiAkhir = Integer.parseInt(b.substring(1, 3));
        return nilai >= nilaiAwal && nilai <= nilaiAkhir;
    } catch (Exception e) {
        return false;
    }
}

private String htmlEscape(String value) {
    if (value == null) {
        return "";
    }
    return value.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("\"", "&quot;").replace("'", "&#39;");
}

